import { DEFAULT_BILLING_SETTINGS, invoiceBreakdown, round2 } from '@/lib/fees'
import type {
  AcspFirm,
  BillingData,
  ClientInvoice,
  Person,
  PlatformInvoice,
  VerificationCase,
} from '@/types/domain'

/*
  Seed billing. Client invoices are issued in the ACSP's name (its own
  numbering and VAT number, generated by the platform on its behalf). Evidence
  One platform-fee invoices only document the £69 plus VAT already deducted
  from referred and B2C payments: one per case for per-case ACSPs, one
  consolidated invoice per completed month for monthly ACSPs. An ACSP's own
  clients carry no platform fee.
*/

/** Invoice number prefix per ACSP, and the number before the first seeded invoice of each year. */
export const INVOICE_PREFIX: Record<string, string> = {
  'acsp-harcourt': 'HLS',
  'acsp-pellrowe': 'AP',
  'acsp-northbank': 'NCL',
  'acsp-ashdown': 'ATS',
  'acsp-fenwick': 'FS',
}

const INVOICE_BASE: Record<string, Record<string, number>> = {
  'acsp-harcourt': { '2025': 11, '2026': 36 },
  'acsp-pellrowe': { '2026': 18 },
  'acsp-northbank': { '2026': 22 },
  'acsp-ashdown': { '2026': 3 },
  'acsp-fenwick': { '2026': 9 },
}

/** Gives every paid case its client invoice number, numbered per ACSP and year in payment order. */
export function assignClientInvoiceIds(
  cases: VerificationCase[],
): VerificationCase[] {
  const paid = cases
    .filter((c) => c.payment?.paidAt)
    .sort((a, b) => a.payment!.paidAt!.localeCompare(b.payment!.paidAt!))
  const counters = new Map<string, number>()
  const ids = new Map<string, string>()
  for (const c of paid) {
    const acspId = c.payment!.payeeAcspId ?? c.acspId
    const year = c.payment!.paidAt!.slice(0, 4)
    const key = `${acspId}:${year}`
    const next = (counters.get(key) ?? INVOICE_BASE[acspId]?.[year] ?? 0) + 1
    counters.set(key, next)
    const prefix = INVOICE_PREFIX[acspId] ?? 'INV'
    ids.set(c.id, `${prefix}-${year}-${String(next).padStart(4, '0')}`)
  }
  return cases.map((c) =>
    c.payment && ids.has(c.id)
      ? { ...c, payment: { ...c.payment, clientInvoiceId: ids.get(c.id) } }
      : c,
  )
}

const monthOf = (iso: string) => iso.slice(0, 7)

export function seedBilling(
  cases: VerificationCase[],
  acsps: AcspFirm[],
  opts: { now?: number; people?: Person[] } = {},
): BillingData {
  const now = opts.now ?? Date.now()
  const settings = structuredClone(DEFAULT_BILLING_SETTINGS)
  const nameOf = (personId: string) => {
    const p = opts.people?.find((x) => x.id === personId)
    return p ? `${p.givenNames} ${p.familyName}` : 'Client'
  }

  const clientInvoices: ClientInvoice[] = cases
    .filter((c) => c.payment?.paidAt && c.payment.clientInvoiceId)
    .map((c) => {
      const pay = c.payment!
      const acsp = acsps.find((a) => a.id === (pay.payeeAcspId ?? c.acspId))
      const b = invoiceBreakdown(pay.amount, settings.vatRate)
      return {
        id: pay.clientInvoiceId!,
        acspId: acsp?.id ?? c.acspId,
        caseId: c.id,
        issuedAt: pay.paidAt!,
        clientName: nameOf(c.personId),
        description: `Identity verification for Companies House, ${c.id}. Issued in the name of ${acsp?.name ?? 'the ACSP'}${acsp?.profile.vatNumber ? `, VAT ${acsp.profile.vatNumber}` : ''}. Evidence One is the ACSP's technology provider.`,
        net: b.net,
        vat: b.vat,
        gross: b.gross,
        paidBy:
          pay.method === 'agent_payment_code'
            ? (pay.payerName ?? 'Referral Partner')
            : nameOf(c.personId),
      }
    })
    .sort((a, b) => a.issuedAt.localeCompare(b.issuedAt))

  // Platform fee invoices cover only referred and B2C cases, which carry the deducted fee.
  const feeCases = cases.filter(
    (c) => c.source !== 'own_client' && (c.payment?.platformFee ?? 0) > 0,
  )
  const draft: Omit<PlatformInvoice, 'id'>[] = []
  for (const acsp of acsps) {
    const mine = feeCases.filter(
      (c) => (c.payment!.payeeAcspId ?? c.acspId) === acsp.id,
    )
    if (acsp.plan.invoiceMode === 'per_case') {
      for (const c of mine) {
        const p = c.payment!
        draft.push({
          acspId: acsp.id,
          mode: 'per_case',
          issuedAt: p.paidAt!,
          caseIds: [c.id],
          net: p.platformFee!,
          vat: p.platformFeeVat ?? 0,
          gross: round2(p.platformFee! + (p.platformFeeVat ?? 0)),
        })
      }
    } else {
      const currentMonth = new Date(now).toISOString().slice(0, 7)
      const months = [
        ...new Set(mine.map((c) => monthOf(c.payment!.paidAt!))),
      ].filter((m) => m < currentMonth)
      for (const m of months.sort()) {
        const group = mine.filter((c) => monthOf(c.payment!.paidAt!) === m)
        const net = round2(
          group.reduce((s, c) => s + c.payment!.platformFee!, 0),
        )
        const vat = round2(
          group.reduce((s, c) => s + (c.payment!.platformFeeVat ?? 0), 0),
        )
        const [y, mo] = m.split('-').map(Number)
        const issued = new Date(Date.UTC(y, mo, 1, 9, 0, 0)).toISOString()
        draft.push({
          acspId: acsp.id,
          mode: 'monthly',
          issuedAt: issued,
          period: m,
          caseIds: group.map((c) => c.id),
          net,
          vat,
          gross: round2(net + vat),
        })
      }
    }
  }
  const platformInvoices: PlatformInvoice[] = draft
    .sort((a, b) => a.issuedAt.localeCompare(b.issuedAt))
    .map((inv, i) => ({
      ...inv,
      id: `EO-PF-${inv.issuedAt.slice(0, 4)}-${String(i + 41).padStart(5, '0')}`,
    }))

  return { settings, clientInvoices, platformInvoices }
}
